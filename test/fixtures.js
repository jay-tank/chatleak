// Shared fixtures for the unit and in-editor tests. Secret-like strings are generated at run time
// from a fixed seed, so no token-shaped literal is ever stored in the source.

function rng(seed) {
  let x = seed >>> 0 || 1;
  return () => {
    x ^= x << 13;
    x >>>= 0;
    x ^= x >>> 17;
    x ^= x << 5;
    x >>>= 0;
    return x;
  };
}

const ALNUM = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
const HEX = "0123456789abcdef";
const UPPER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";

function fake(prefix, len, seed, alphabet) {
  const r = rng(seed);
  const a = alphabet || ALNUM;
  let s = "";
  for (let i = 0; i < len; i++) s += a[r() % a.length];
  return prefix + s;
}

